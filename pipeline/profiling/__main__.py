"""Profile one university's instance: metrics + automatic remarks -> JSON and Markdown.

    cd pipeline
    python -m profiling instances/hcmut                     # -> profiling/reports/hcmut/
    python -m profiling instances/toy --out some/folder

Reads only the canonical files (instances/SCHEMA.md): every curriculum (with its
graduation.json), the optional catalog.json (courses and relations of all programs) and
every student file.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from instances.loader import load_university
from profiling.catalog import profile_catalog
from profiling.curriculum import profile_curriculum
from profiling.remarks import catalog_remarks, curriculum_remarks, students_remarks
from profiling.students import profile_students

REPORTS = Path(__file__).resolve().parent / "reports"


def profile_university(root: Path) -> dict[str, Any]:
    uni = load_university(root)
    out: dict[str, Any] = {"university": root.name, "curricula": {}, "students": {}, "catalog": None}
    for cid, entry in uni.curricula.items():
        p = profile_curriculum(entry["curriculum"], entry.get("graduation"))
        p["remarks"] = curriculum_remarks(p)
        out["curricula"][cid] = p
    if (root / "catalog.json").is_file():
        c = profile_catalog(json.loads((root / "catalog.json").read_text(encoding="utf-8")))
        c["remarks"] = catalog_remarks(c)
        out["catalog"] = c
    for stem, doc in uni.students.items():
        s = profile_students(doc, uni.policy.get("grading"))
        s["remarks"] = students_remarks(s)
        out["students"][stem] = s
    return out


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.0%}"


def to_markdown(prof: dict[str, Any]) -> str:
    md = [f"# Input profile: {prof['university']}", "",
          "Generated by `python -m profiling`. Numbers are computed from the instance files; "
          "remarks are rule-based (profiling/remarks.py) and need a human check.", ""]
    for cid, p in prof["curricula"].items():
        size, rel, fit, ch, off = p["size"], p["relations"], p["calendar_fit"], p["choice"], p["offering"]
        md += [f"## Curriculum {cid}", "", p.get("name") or "", "",
               "| Metric | Value |", "|---|---|",
               f"| Courses (condition courses) | {size['courses']} ({size['condition_courses']}) |",
               f"| Degree credits / listed credits | {size['degree_credits']} / {size['listed_credits']} |",
               f"| Mandatory credits | {ch['mandatory_credits']} |",
               f"| Elective groups / free-elective credits | {len(ch['elective_groups'])} / {ch['free_elective_credits']} |",
               f"| Share of degree chosen by the student | {_pct(ch['chosen_credit_share'])} |",
               f"| Relations by type | {rel['by_type']} |",
               f"| Hard relations per course | {rel['hard_per_course']} |",
               f"| Courses in a hard relation | {_pct(rel['share_of_courses_in_hard_relation'])} |",
               f"| Longest prerequisite chain | {rel['longest_prerequisite_chain']} ({' -> '.join(rel['longest_chain_example'])}) |",
               f"| Regular terms: nominal / by load / by chain | {fit['nominal_regular_terms']} / "
               f"{fit['terms_needed_by_max_load']} / {fit['terms_needed_by_chain']} |",
               f"| Load needed on time (allowed) | {fit['mean_load_needed']} ({fit['min_load']}-{fit['max_load']}) |",
               f"| Typical term known | {_pct(off['typical_term_known'])} |",
               f"| Offering known: regular / summer history | {_pct(off['offered_terms_known'])} / "
               f"{_pct(off['summer_history_known'])} |",
               f"| Majors (mean overlap) | {p['majors']['count']} ({p['majors']['mean_jaccard_overlap']}) |",
               ""]
        if ch["elective_groups"]:
            md += ["| Elective group | Pool courses | Pool credits | Required credits | Slack |", "|---|---|---|---|---|"]
            md += [f"| {g['id']} {g['name'] or ''} | {g['pool_courses']} | {g['pool_credits']} | "
                   f"{g['required_credits']:g} | {g['slack']} |" for g in ch["elective_groups"]]
            md.append("")
        if rel["top_dependents"]:
            md.append("Courses most others depend on: " + ", ".join(
                f"{d['course']} ({d['dependents']})" for d in rel["top_dependents"]) + ".")
            md.append("")
        md += ["### Remarks", ""] + [f"- {r}" for r in p["remarks"] or ["None."]] + [""]
    if prof["catalog"]:
        c = prof["catalog"]
        md += ["## All programs (catalog.json)", "",
               f"{c['programs']} programs; courses per program {c['courses_per_program']}; "
               f"relation types {c['relation_types']}; hard relations per course {c['hard_per_course']}.", "",
               "### Remarks", ""] + [f"- {r}" for r in c["remarks"] or ["None."]] + [""]
    for stem, s in prof["students"].items():
        md += [f"## Students: {stem}", "",
               f"{s['students']} students ({s['sources']}), {s['attempts']} attempts, outcomes {s['outcomes']}, "
               f"{s['attempts_without_term']} without term, {s['attempts_with_grade']} with grade, "
               f"{s['retaken_courses']} retaken course(s).", "",
               "### Remarks", ""] + [f"- {r}" for r in s["remarks"] or ["None."]] + [""]
    return "\n".join(md)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("university", type=Path, help="instances/<university>")
    ap.add_argument("--out", type=Path, default=None, help="default profiling/reports/<university>")
    args = ap.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    prof = profile_university(args.university)
    out = args.out or REPORTS / args.university.name
    out.mkdir(parents=True, exist_ok=True)
    (out / "profile.json").write_text(json.dumps(prof, indent=1, ensure_ascii=False), encoding="utf-8")
    (out / "report.md").write_text(to_markdown(prof), encoding="utf-8")
    print(f"wrote {out / 'profile.json'}\nwrote {out / 'report.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
